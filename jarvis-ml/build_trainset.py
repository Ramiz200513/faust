def add(phrase, tgt, cat, src="template"):
    phrase = " ".join(phrase.split())
    if phrase:
        ROWS.append({"phrase": phrase, "target": tgt, "cat": cat, "src": src})


def pick(seq, k):
    seq = list(seq)
    return seq if len(seq) <= k else R.sample(seq, k)


def is_latin(s):
    return bool(re.fullmatch(r"[A-Za-z0-9 .+\-]+", s))


