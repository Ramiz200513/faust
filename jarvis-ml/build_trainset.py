def gen_distill():
    path = os.path.join(DATA, "distill.jsonl")
    if not os.path.exists(path):
        return
    for row in read_jsonl(path):
        # Дважды: после vary() это два написания одной фразы. Таких фраз мало рядом с
        # шаблонами, а они ближе всего к тому, что модель услышит в работе.
        for _ in range(2):
            add(row["phrase"], row["target"], row["cat"], "distill")


# =============================================================================
#  Разнообразие написания: регистр, знаки, опечатки, обращение
# =============================================================================
def typo(s):
    words = s.split()
    idx = [i for i, w in enumerate(words) if len(w) >= 5 and w.isalpha()]
    if not idx:
        return s
    i = R.choice(idx)
    w = words[i]
    j = R.randint(1, len(w) - 3)
    words[i] = w[:j] + w[j + 1] + w[j] + w[j + 2:] if R.random() < 0.6 else w[:j] + w[j + 1:]
    return " ".join(words)


def vary(phrase):
    """Тот же смысл в другом написании: телефон присылает и «Открой ютуб.», и «открой ютуб»."""
    r = R.random()
    p = phrase
    if R.random() < 0.06:
        p = R.choice(["фауст, ", "фауст ", "Фауст, "]) + p
    if r < 0.60:
        p = p.lower()
    elif r < 0.85:
        p = p[:1].upper() + p[1:] + R.choice(["", ".", "", "!"])
    if R.random() < 0.05:
        p = typo(p)
    return p


# Слова, которые не меняют смысл просьбы: с ними и без них фраза — «та же самая».
FILLERS = {"пожалуйста", "плиз", "быстро", "срочно", "сейчас", "слушай", "будь", "добр", "можешь", "а", "ну", "ка",
           "эй", "фауст", "если", "не", "сложно", "мне", "please"}


def core(phrase):
    """Ядро фразы для сравнения с экзаменом: нормальный вид без вежливых слов."""
    return " ".join(w for w in norm(phrase).split() if w not in FILLERS)


