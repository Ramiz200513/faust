TEACHER_CACHE = os.path.join(DATA, "teacher_cache.json")
TEACHER_FAILS = [0]   # сколько запросов подряд не удалось
STYLE = ("Пиши так, как люди на самом деле говорят голосовому ассистенту или печатают в чат: разговорно, "
         "по-разному длинно, с разным порядком слов, иногда со сленгом, иногда вежливо, иногда коротко и резко. "
         "Без кавычек и нумерации. Ответ — только JSON-массив строк.")


def teacher(key, prompt, cache):
    """Один запрос к Gemini через релей; ответы кэшируются на диске — повторный запуск бесплатен."""
    if key in cache:
        return cache[key]
    # Gemini недоступен (нет интернета, кончилась квота) — не тратим время на
    # остальные запросы: то, что уже в кэше, используется, остальное доберём в другой раз.
    if TEACHER_FAILS[0] >= 3:
        return []
    try:
        text = relay_post("/api/admin/llm/generate", {"prompt": prompt, "temperature": 1.0, "json": True})["text"]
        items = json.loads(text)
        items = [str(x).strip() for x in items if isinstance(x, (str, int, float)) and str(x).strip()]
    except Exception as e:
        TEACHER_FAILS[0] += 1
        print(f"  учитель: «{key}» не получилось ({e})"
              + (" — дальше учителя не спрашиваю" if TEACHER_FAILS[0] == 3 else ""))
        return []
    TEACHER_FAILS[0] = 0
    cache[key] = items
    with open(TEACHER_CACHE, "w", encoding="utf-8") as f:
        json.dump(cache, f, ensure_ascii=False, indent=0)
    return items


