def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-teacher", action="store_true", help="без перефразировок Gemini")
    args = ap.parse_args()

    gen_volume(); gen_sites(); gen_apps(); gen_kill(); gen_simple()
    gen_browser(); gen_screen(); gen_contrast(); gen_unknown()
    gen_wrapped(); gen_policy(); gen_web_files(); gen_many(); gen_media()
    if not args.no_teacher:
        gen_teacher()
    gen_distill()
    lessons = os.path.join(DATA, "lessons.jsonl")
    if os.path.exists(lessons):   # уроки из работы — см. retrain.py
        for row in read_jsonl(lessons):
            add(row["phrase"], row["target"], row.get("cat", "lesson"), "lesson")

    for row in ROWS:
        if row["src"] != "lesson":
            row["phrase"] = vary(row["phrase"])

    # --- экзамен в обучение не попадает ---
    # Сравниваем «ядра» фраз: без вежливых слов и обращения. Иначе в обучении
    # осталась бы экзаменационная «сделай скриншот» в виде «сделай скриншот пожалуйста».
    test = set()
    for name in ("intent_test.jsonl", "intent_test_b.jsonl"):
        path = os.path.join(RELAY_EVAL, name)
        if os.path.exists(path):
            test |= {core(c["phrase"]) for c in read_jsonl(path)}
    before = len(ROWS)
    rows = [r for r in ROWS if core(r["phrase"]) not in test]
    leaked = before - len(rows)

    # --- одна фраза — один ответ ---
    # Учитель иногда придумывает фразу с другим смыслом, чем просили («звук на
    # максимум» в ответ на «сделай погромче»), а разметка Gemini иногда расходится с
    # нашими правилами. Если та же фраза есть в шаблонах, верим шаблону: там ответ
    # известен точно. Остальные противоречия выбрасываем целиком.
    from_gemini = ("teacher", "distill")
    exact = {}
    for r in rows:
        if r["src"] not in from_gemini:
            exact.setdefault(norm(r["phrase"]), set()).add(r["target"])
    overruled = [r for r in rows if r["src"] in from_gemini and norm(r["phrase"]) in exact
                 and r["target"] not in exact[norm(r["phrase"])]]
    rows = [r for r in rows if r["src"] not in from_gemini or norm(r["phrase"]) not in exact
            or r["target"] in exact[norm(r["phrase"])]]
    by_phrase = {}
    for r in rows:
        by_phrase.setdefault(norm(r["phrase"]), set()).add(r["target"])
    conflicts = {p for p, t in by_phrase.items() if len(t) > 1}
    rows = [r for r in rows if norm(r["phrase"]) not in conflicts]
    seen, unique = set(), []
    for r in rows:
        key = (r["phrase"], r["target"])
        if key not in seen:
            seen.add(key)
            unique.append(r)
    rows = unique

    R.shuffle(rows)
    # dev — отложенная часть фраз УЧИТЕЛЯ: они естественнее шаблонов, и модель их не
    # видела. По ним подбирается порог уверенности (экзамен для этого трогать нельзя:
    # порог, подобранный на экзамене, был бы подгонкой под экзамен).
    teacher_rows = [r for r in rows if r["src"] == "teacher"]
    dev = teacher_rows[:len(teacher_rows) // 8]
    dev_keys = {norm(r["phrase"]) for r in dev}
    rows_train = [r for r in rows if norm(r["phrase"]) not in dev_keys]
    n_val = max(200, len(rows_train) // 16)
    val, train = rows_train[:n_val], rows_train[n_val:]
    # Урок важнее рядового шаблона: показываем его трижды. Делается здесь, а не при
    # добавлении: одинаковые строки выше считаются повторами и схлопываются в одну.
    train += [r for r in train if r["src"] == "lesson"] * 2
    R.shuffle(train)
    write_jsonl(os.path.join(DATA, "train.jsonl"), train)
    write_jsonl(os.path.join(DATA, "val.jsonl"), val)
    write_jsonl(os.path.join(DATA, "dev.jsonl"), dev)

    print(f"собрано {before}; совпало с экзаменом и выброшено: {leaked}; противоречивых фраз: {len(conflicts)}")
    print(f"train: {len(train)}, val: {len(val)}, dev (отложенные фразы учителя): {len(dev)}")
    stat = {}
    for r in rows:
        stat.setdefault(r["cat"], {}).setdefault(r["src"], 0)
        stat[r["cat"]][r["src"]] += 1
    for cat in sorted(stat):
        total = sum(stat[cat].values())
        print(f"  {cat:15s} {total:5d}   " + ", ".join(f"{s}: {n}" for s, n in sorted(stat[cat].items())))
    if conflicts:
        print("противоречия (первые 10):", list(conflicts)[:10])
    if overruled:
        print(f"фраз Gemini, где ответ расходится с шаблоном (взят шаблон): {len(overruled)}")
        for r in overruled[:15]:
            print(f"   «{r['phrase']}»: Gemini {r['target']}, шаблон {sorted(exact[norm(r['phrase'])])[0]}")


if __name__ == "__main__":
    main()
