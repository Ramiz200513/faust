package com.jarvis.agent.plan;

/**
 * Проверка результата подзадачи ПОСЛЕ того, как исполнитель сказал «готово».
 *
 * <h2>Зачем</h2>
 * На прогонах 30.09 агент трижды назвал задачу выполненной, когда она не была
 * выполнена: нашёл курс, но в Блокнот не записал; отказался на странице
 * входа. В одиночной задаче это просто неверная цифра в журнале. В плане
 * хуже: следующая подзадача строится на ложном итоге предыдущей — и,
 * например, пытается отправить файл, который так и не сохранился.
 *
 * <p>Поэтому итог исполнителя проверяется независимо от него самого: кодом
 * (появился ли файл) и отдельным взглядом модели на окно программы. Не
 * прошла проверка — подзадача считается неудачной, и план перестраивается.
 */
public interface StepVerifier {

    /**
     * Результат проверки.
     *
     * @param ok     true — подтверждено; false — опровергнуто; null — понять не удалось
     *               (тогда верим исполнителю: неуверенная проверка не должна ломать работающее)
     * @param reason что именно увидела проверка — идёт в трейс и в итог подзадачи
     */
    record Check(Boolean ok, String reason) {}

    /** @return null, если у подзадачи нечего проверять */
    Check verify(PlanStep step, String summary);

    /** Без проверок — для тестов и прежнего поведения. */
    StepVerifier NONE = (step, summary) -> null;
}
