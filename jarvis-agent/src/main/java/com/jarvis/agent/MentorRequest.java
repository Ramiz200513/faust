package com.jarvis.agent;

import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Просьба «научи меня, а не сделай за меня»: «Фауст, покажи, как включить экранную лупу».
 *
 * <h2>Зачем отдельный разбор</h2>
 * Обычная задача агенту — «включи экранную лупу»: агент сам кликает. Просьба с «покажи,
 * как …» значит другое: человек хочет научиться, кликать будет он, а агент — показывать
 * стрелкой, куда (режим наставника, {@code vision.MentorSession}). Отличает их только начало
 * фразы, поэтому разбор — правилом, без модели: быстро, бесплатно и всегда одинаково.
 *
 * <p>Релей отдаёт агенту фразу как есть (правило MENTOR в StubIntentParser), а агент здесь
 * вынимает саму задачу: «покажи, как включить экранную лупу» → «включить экранную лупу».
 *
 * <p>Не путать с «покажи рабочий стол», «покажи коммиты», «покажи папку» — в них нет «как»,
 * это обычные команды.
 */
public final class MentorRequest {

    private MentorRequest() {}

    /** Включён ли режим наставника (mentor.enabled=false — «покажи, как» выполняется как обычная задача). */
    public static final String ENABLED = "mentor.enabled";

    /** Глагол в неопределённой форме (-ть/-ти/-чь, -ся/-сь), кроме «быть/жить/стать» — разговорных. */
    private static final String INFINITIVE = "(?!(?:быть|жить|стать)(?:\\s|$))[а-яё-]+(?:ть|ти|чь)(?:ся|сь)?";

    // (?iu): регистр без учёта и для кириллицы. Обращение и вежливые слова в начале — необязательны.
    private static final Pattern REQUEST = Pattern.compile(
            "(?iu)^\\s*(?:(?:фауст|faust|джарвис)[,!.\\s]+)?(?:пожалуйста[,\\s]+|будь\\s+добр[,\\s]+|слушай[,\\s]+)?"
            + "(?:"
            + "(?:покажи|подскажи|объясни|расскажи)(?:[,\\s]+мне)?[,\\s]+(?:пожалуйста[,\\s]+)?как(?:\\s+мне)?\\s+"
            + "|научи(?:[,\\s]+меня)?(?:[,\\s]+пожалуйста)?[,\\s]+(?:как\\s+)?"
            + "|как\\s+(?:мне\\s+)?(?:самому|самой|самостоятельно)\\s+"
            // Голый вопрос «как включить экранную лупу?» (живой урок 19.11: так и говорят).
            // Сразу после «как» — глагол в неопределённой форме, иначе «как дела» стало бы уроком.
            // Тот же шаблон, что StubIntentParser.INFINITIVE на релее.
            + "|(?:а\\s+)?как(?:\\s+(?:мне|можно|же))?\\s+(?=" + INFINITIVE + "(?:\\s|$))"
            + ")"
            + "(.+?)[\\s.!?]*$");

    /**
     * Задача, которой учим, или null — это не просьба научить.
     * «Фауст, покажи мне, как включить лупу» → «включить лупу».
     */
    public static String task(String goal) {
        if (goal == null) return null;
        Matcher m = REQUEST.matcher(goal);
        if (!m.matches()) return null;
        String task = m.group(1).strip()
                .replaceAll("(?iu)[,\\s]+пожалуйста$", "")
                .replaceAll("(?iu)^(?:это|это\\s+сделать)\\s*[:,]?\\s*", "");
        // «научи меня» без самой задачи или «покажи, как дела» — не про компьютер.
        // «научи меня» без задачи: регулярное выражение отдаёт «меня» как задачу — это не она.
        if (task.length() < 3 || task.toLowerCase(Locale.ROOT)
                .matches("дела|ты|жизнь|у тебя дела|меня|мне|чему-нибудь|чему нибудь|чему-то|всему")) return null;
        return task;
    }

    /** Просьба научить и режим включён. */
    public static boolean applies(String goal) {
        return AgentSettings.flag(ENABLED, true) && task(goal) != null;
    }
}
